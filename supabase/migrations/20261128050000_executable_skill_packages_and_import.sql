-- First-class executable skill packages: metadata, source provenance, assets and bounded execution manifests.
create table if not exists public.skill_assets (
  id bigint generated by default as identity primary key,
  version_id uuid not null references public.skill_versions(id) on delete cascade,
  asset_path text not null,
  asset_type text not null check (asset_type in ('instruction','script','code','config','reference','test','other')),
  content_text text,
  source_uri text,
  source_sha256 text,
  executable boolean not null default false,
  mode text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(version_id, asset_path)
);

create index if not exists skill_assets_version_idx on public.skill_assets(version_id);
create index if not exists skill_assets_executable_idx on public.skill_assets(version_id, executable);

alter table public.skill_assets enable row level security;

